% Description:
%   Finds the nearest sampled timestamp index for each annotation marker
%   to align events with plotted sensor signals.

function i_marcas = get_indices_plot(tsmillis, t_marcas)
    % Initialize a matrix to store the differences.
    diferencias = zeros(length(tsmillis), length(t_marcas));
    
    % Compute the absolute difference for each marker timestamp.
    for i = 1:length(t_marcas)
        diferencias(:, i) = abs(tsmillis - t_marcas(i));
    end
    
    [min_value, i_marcas] = min(diferencias);
end
